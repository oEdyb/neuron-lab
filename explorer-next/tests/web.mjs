import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
const browser=await chromium.launch({headless:true})
const checks=[],errors=[]
await mkdir('shots/web',{recursive:true})
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}}),requests=[]
 page.on('pageerror',e=>errors.push(e.message))
 page.on('request',r=>{if(/connections\/L\d+\.bin/.test(r.url()))requests.push(r.url())})
 await page.goto('http://127.0.0.1:8792/#L17-N5244')
 await page.waitForFunction(()=>window.neuronNext)
 assert.equal(requests.length,0)
 await page.getByRole('radio',{name:'Web',exact:true}).click()
 await page.locator('.web-table tbody tr').first().waitFor()
 assert.equal(await page.locator('.web-table tbody tr').count(),48)
 assert.equal(await page.locator('.web-node').count(),16)
 assert.equal(requests.length,1)
 assert.match(requests[0],/L17.bin$/)
 checks.push('Web loads only the selected layer connection binary; 48 rows, 16 graph neighbors')
 for(const viewport of [{width:1440,height:900},{width:1920,height:1080}]){
  await page.setViewportSize(viewport)
  await page.screenshot({path:`shots/web/web-${viewport.width}x${viewport.height}.png`})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  const boxes=await page.locator('.web-node').evaluateAll(nodes=>nodes.map(n=>{const r=n.getBoundingClientRect();return {x:r.x,y:r.y,bottom:r.bottom,right:r.right}}))
  for(const r of boxes){assert(r.x>=0&&r.right<=viewport.width&&r.y>=0&&r.bottom<=viewport.height)}
 }
 checks.push('1440×900 and 1920×1080: graph nodes within viewport, no document overflow')
 await page.setViewportSize({width:1440,height:900})
 await page.locator('.web-node').first().focus()
 await page.getByRole('tooltip').waitFor()
 assert.match(await page.getByRole('tooltip').innerText(),/代表/)
 await page.screenshot({path:'shots/web/hover-1440x900.png'})
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'About connection estimates'}).focus()
 await page.getByRole('tooltip',{name:/Estimated from weights/}).waitFor()
 assert.match(await page.getByRole('tooltip',{name:/Estimated from weights/}).innerText(),/Estimated from weights/)
 await page.keyboard.press('Escape')
 checks.push('Node words and estimate limitations accessible on keyboard focus')
 const star=page.getByRole('button',{name:'Star L12 N5177',exact:true})
 await star.click();assert.equal(await star.getAttribute('aria-pressed'),'true')
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('neuron-next-favourites')))
 assert(saved.some(n=>n.layer===12&&n.n===5177))
 checks.push('Star toggles independently and is saved in localStorage')
 await page.getByRole('button',{name:'Strength · z'}).click()
 const strengths=await page.locator('.web-strength').allTextContents()
 assert(+strengths[0]<=+strengths.at(-1))
 await page.getByRole('button',{name:'Neuron',exact:true}).click()
 assert.equal(await page.locator('.web-table th').first().getAttribute('aria-sort'),'ascending')
 await page.getByRole('button',{name:'Top + words'}).click()
 assert.equal(await page.locator('.web-table th').nth(3).getAttribute('aria-sort'),'ascending')
 await page.getByRole('button',{name:'Effect',exact:true}).click()
 assert.equal(await page.locator('.web-table th').nth(1).getAttribute('aria-sort'),'ascending')
 await page.locator('.web-list').getByRole('radio',{name:'Upstream',exact:true}).click()
 assert.equal(await page.locator('.web-table tbody tr').count(),24)
 await page.locator('.web-list').getByRole('radio',{name:'All 48',exact:true}).click()
 checks.push('All four columns sort; direction filter keeps 24 links per side')
 await page.locator('.web-node').first().click()
 await page.waitForFunction(()=>document.querySelector('.web-toolbar strong')?.textContent==='L14 N4826')
 await page.locator('.web-table tbody tr').first().waitFor()
 await page.getByRole('button',{name:'Back',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('.web-toolbar strong')?.textContent==='L17 N5244')
 await page.locator('.web-table tbody tr').first().waitFor()
 assert.equal(requests.filter(r=>r.endsWith('/L17.bin')).length,1)
 checks.push('Graph click recenters; Back restores center and reuses cached binary')
 await page.getByRole('button',{name:'Add L12 N5177 to chat',exact:true}).click()
 await page.getByRole('tab',{name:'Chat',exact:true}).waitFor()
 assert.equal(await page.getByRole('tab',{name:'Chat',exact:true}).getAttribute('data-state'),'active')
 const chats=await page.evaluate(()=>JSON.parse(localStorage.getItem('neuron-next-chats')))
 assert.equal(chats.length,1)
 await page.getByRole('button',{name:'Add L19 N4137 to chat',exact:true}).click()
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('neuron-next-chats'))?.[0] && (JSON.parse(localStorage.getItem('neuron-next-chats'))[0].steerSet??JSON.parse(localStorage.getItem('neuron-next-chats'))[0].pushes).some(n=>n.layer===19&&n.n===4137))
 const updated=await page.evaluate(()=>JSON.parse(localStorage.getItem('neuron-next-chats')))
 assert((updated[0].steerSet??updated[0].pushes).some(n=>n.layer===19&&n.n===4137))
 checks.push('Add to chat creates a saved chat or adds a push; no model generation sent')
 for(const [layer,side,message] of [[0,'Upstream','No earlier layers'],[23,'Downstream','No later layers']]){
  await page.evaluate(layer=>window.neuronNext.select({layer,n:1}),layer)
  await page.getByText(message,{exact:true}).waitFor()
  await page.locator('.web-list').getByRole('radio',{name:side,exact:true}).click()
  assert.equal(await page.locator('.web-table tbody tr').count(),0)
 }
 checks.push('First and last layer show empty upstream/downstream correctly')
 await page.getByRole('radio',{name:'Tower',exact:true}).click()
 assert.equal(await page.locator('.map-surface').isVisible(),true)
 await page.getByRole('radio',{name:'Plane',exact:true}).click()
 assert.equal(await page.locator('.map-surface').isVisible(),true)
 checks.push('Tower and Plane remain accessible after Web navigation')
 assert.deepEqual(errors,[])
 await writeFile('shots/web/ui-checks.json',JSON.stringify({url:'http://127.0.0.1:8792',checks,errors},null,2)+'\n')
 console.log(JSON.stringify({checks,errors},null,2))
}finally{await browser.close()}
